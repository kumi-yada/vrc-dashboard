const TRANSLATIONS: Record<Locale, Messages> = { en, ja, zh };

function loadLocale(): Locale {
  try {
    const raw = typeof localStorage === "undefined" ? null : localStorage.getItem(STORAGE_KEY);
    if (raw === "en" || raw === "ja" || raw === "zh") return raw;
  } catch {
    // fall through to default
  }
  return "en";
}

function applyLocaleTag(tag: string): void {
  if (typeof document === "undefined") return;
  document.documentElement.lang = tag;
}

function currentTag(): string {
  return LOCALES.find((l) => l.id === locale)?.tag ?? "en-US";
}

let locale = $state<Locale>(loadLocale());
applyLocaleTag(currentTag());

export function getI18n() {
  return {
    get locale() {
      return locale;
    },
    get tag() {
      return currentTag();
    },
  };
}

export function setLocale(next: Locale): void {
  if (!LOCALES.some((l) => l.id === next)) return;
  locale = next;
  applyLocaleTag(currentTag());
  try {
    if (typeof localStorage !== "undefined") {
      localStorage.setItem(STORAGE_KEY, next);
    }
  } catch {
    // Ignore storage errors and keep the UI responsive.
  }
}

export function t(
  key: MessageKey | (string & {}),
  params?: Record<string, string | number>,
): string {
  const table: Messages = TRANSLATIONS[locale] ?? TRANSLATIONS.en;
  let value = (table as Record<string, string>)[key] ?? en[key as MessageKey] ?? key;
  if (params) {
    for (const [name, paramValue] of Object.entries(params)) {
      value = value.replaceAll(`{${name}}`, String(paramValue));
    }
  }
  return value;
}

/** Plural-aware translation: picks the singular key for count === 1. */
export function tp(
  oneKey: MessageKey,
  otherKey: MessageKey,
  count: number,
  params: Record<string, string | number> = {},
): string {
  return t(count === 1 ? oneKey : otherKey, { count, ...params });
}
